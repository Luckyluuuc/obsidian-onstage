import asyncio, pathlib
from playwright.async_api import async_playwright
root = pathlib.Path("/home/claude/onstage/test")
VIS = ".onstage-slide:not(.onstage-measure)"
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--allow-file-access-from-files"])
        pg = await b.new_page(viewport={"width": 1280, "height": 720})
        errs=[]; pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto((root / ".out/index.html").as_uri())
        await pg.evaluate("window.ready")
        await pg.evaluate("([s,l]) => present(s,l)", [(root/"sample.md").read_text(), 8])
        await pg.wait_for_timeout(200)
        await pg.mouse.move(640, 360); await pg.click(".onstage-edit-btn")
        await pg.wait_for_timeout(200)
        await pg.keyboard.type("\n- premier ajout")
        await pg.wait_for_timeout(700)
        s = await pg.evaluate("window.SRC")
        print("written while typing:", "- premier ajout" in s, "| still editing:", await pg.locator(".onstage-source-editor").count()==1)
        await pg.keyboard.type("\n- second ajout")
        await pg.wait_for_timeout(700)
        s = await pg.evaluate("window.SRC")
        print("second written:", "- second ajout" in s, "| first not duplicated:", s.count("- premier ajout")==1)
        await pg.keyboard.press("Backspace", delay=10)
        for _ in range(14): await pg.keyboard.press("Backspace")
        await pg.wait_for_timeout(700)
        s = await pg.evaluate("window.SRC")
        print("deletion synced:", "- second ajout" not in s and "- premier ajout" in s)
        await pg.keyboard.press("Escape")
        await pg.wait_for_timeout(400)
        s = await pg.evaluate("window.SRC").split("\n") if False else (await pg.evaluate("window.SRC")).split("\n")
        i = s.index("## Résultats du chapitre 2")
        print("final section:", s[i:i+7])
        print("slide shows:", "premier ajout" in await pg.locator(f"{VIS} .onstage-flow").inner_text(), "errors:", errs)
        await b.close()
asyncio.run(main())
