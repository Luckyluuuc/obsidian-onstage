import asyncio, pathlib
from playwright.async_api import async_playwright
root = pathlib.Path("/home/claude/onstage/test")
VIS = ".onstage-slide:not(.onstage-measure)"
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path="/usr/bin/google-chrome", args=["--allow-file-access-from-files"])
        pg = await b.new_page(viewport={"width": 1440, "height": 900})
        errs=[]; pg.on("pageerror", lambda e: errs.append(str(e)))
        await pg.goto((root / ".out/index.html").as_uri())
        await pg.evaluate("window.ready")
        await pg.evaluate("([s,l]) => present(s,l)", [(root/"sample.md").read_text(), 8])
        await pg.wait_for_timeout(300)
        box = await pg.locator(".onstage-canvas").bounding_box()
        print("canvas fills 16:10 screen:", [round(v) for v in (box["x"], box["y"], box["width"], box["height"])])
        await pg.screenshot(path=str(root/".out/fill-1610.png"))
        t0 = await pg.locator(f"{VIS} .onstage-title").inner_text()
        await pg.mouse.click(1100, 450); await pg.wait_for_timeout(60)
        t1 = await pg.locator(f"{VIS} .onstage-title").inner_text()
        print("click immediate:", t0, "->", t1)
        await pg.mouse.dblclick(1100, 450); await pg.wait_for_timeout(300)
        print("dblclick no editor:", await pg.locator(".onstage-source-editor").count()==0)
        await pg.evaluate("view.goToLine(8)"); await pg.evaluate("view.rootEl.focus()")
        fs0 = await pg.evaluate(f"getComputedStyle(document.querySelector('{VIS} .onstage-flow')).fontSize")
        for _ in range(4): await pg.keyboard.press("+")
        await pg.wait_for_timeout(200)
        fs1 = await pg.evaluate(f"getComputedStyle(document.querySelector('{VIS} .onstage-flow')).fontSize")
        print("zoom +:", fs0, "->", fs1, "| flash:", await pg.inner_text(".onstage-zoom-flash"))
        await pg.screenshot(path=str(root/".out/zoomed.png"))
        await pg.keyboard.press("0"); await pg.wait_for_timeout(200)
        print("zoom reset:", await pg.evaluate(f"getComputedStyle(document.querySelector('{VIS} .onstage-flow')).fontSize"))
        await pg.set_viewport_size({"width": 1280, "height": 720}); await pg.wait_for_timeout(300)
        box = await pg.locator(".onstage-canvas").bounding_box()
        print("16:9 after resize:", [round(v) for v in (box["width"], box["height"])], "errors:", errs)
        await b.close()
asyncio.run(main())
