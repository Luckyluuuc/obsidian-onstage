export type I18nKey = keyof Dict;

export function t(key: I18nKey): string {
	const lang = (moment.locale() || "en").toLowerCase();
	const text = lang.startsWith("fr") ? fr[key] ?? en[key] : en[key];
	// Shortcut names as the user's keyboard shows them.
	return text.replace(/\{mod\}/g, Platform.isMacOS ? "Cmd" : "Ctrl");
}
